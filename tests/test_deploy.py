class SplitTests(unittest.TestCase):
    def test_basic_and_comments_and_strings(self):
        sql = "-- header; comment\nCREATE TABLE t (a INT);\n/* block; */ INSERT INTO t VALUES (1), (2);\nSELECT 'x;y', `we;ird` FROM t;\n-- trailing only"
        self.assertEqual(split_statements(sql), ['-- header; comment\nCREATE TABLE t (a INT)', "/* block; */ INSERT INTO t VALUES (1), (2)", "SELECT 'x;y', `we;ird` FROM t"])

    def test_procedure_body_stays_together(self):
        parts = split_statements(PROC + '\nSELECT 1;')
        self.assertEqual(len(parts), 2)
        self.assertTrue(parts[0].startswith('CREATE OR REPLACE PROCEDURE') and parts[0].endswith('END'))
        self.assertEqual(parts[1], 'SELECT 1')

    def test_case_expression_and_dollar_body(self):
        sql = "SELECT CASE WHEN a THEN 1 END FROM t; CREATE FUNCTION f() RETURNS INT LANGUAGE PYTHON AS $$ x=1; return x $$; SELECT 2"
        self.assertEqual(len(split_statements(sql)), 3)

    def test_escaped_quotes(self):
        self.assertEqual(split_statements("SELECT 'it''s; ok'; SELECT 'a\\';b'"), ["SELECT 'it''s; ok'", "SELECT 'a\\';b'"])

    def test_deployable_files_skips_non_sql(self):
        conv = {'files': [{'name': 'a.sql', 'sql': 'SELECT 1'}, {'name': 'migration-coverage.json', 'sql': '{}', 'kind': 'coverage_report'},
                          {'name': 'nb.py', 'sql': 'x', 'kind': 'notebook'}, {'name': 'plan.sql', 'sql': 'x', 'kind': 'migration_plan'}]}
        self.assertEqual([f['name'] for f in deployable_files(conv)], ['a.sql'])


class NullFixTests(unittest.TestCase):
    def test_removes_bare_null_only(self):
        out, n = strip_null_constraints("CREATE TABLE `dbo`.`u` (`id` BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1), `c` INT NULL, `d` DECIMAL(10,2) NULL, `e` STRING DEFAULT NULL, `f` STRING NULL COMMENT 'may be NULL', CONSTRAINT k CHECK (c IS NULL OR c > 0))")
        self.assertEqual(n, 3)
        self.assertEqual(out, "CREATE TABLE `dbo`.`u` (`id` BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1), `c` INT, `d` DECIMAL(10,2), `e` STRING DEFAULT NULL, `f` STRING COMMENT 'may be NULL', CONSTRAINT k CHECK (c IS NULL OR c > 0))")

    def test_leaves_other_statements(self):
        for sql in ("CREATE TABLE t AS SELECT NULL AS x", "INSERT INTO t VALUES (NULL, 1)", "SELECT NULL"):
            self.assertEqual(strip_null_constraints(sql), (sql, 0))


class DeployTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.store = RunService(Path(self.temp.name) / 'runs.db')
        self.calls, self.fail_on, self.polls = [], None, {}

        def transport(host, token, method, path, payload=None):
            self.calls.append((method, path, payload))
            if method == 'POST' and path == '/api/2.0/sql/statements':
                n = sum(1 for c in self.calls if c[1] == path)
                sid = f'stmt-{n}'
                if self.fail_on and self.fail_on in payload['statement']:
                    return {'statement_id': sid, 'status': {'state': 'FAILED', 'error': {'message': '[TABLE_OR_VIEW_NOT_FOUND] missing'}}}
                if 'SLOW' in payload['statement']:
                    return {'statement_id': sid, 'status': {'state': 'RUNNING'}}
                return {'statement_id': sid, 'status': {'state': 'SUCCEEDED'}}
            if method == 'GET' and path == '/api/2.0/preview/scim/v2/Me':
                return {'userName': 'radhika@example.com'}
            if method == 'GET':
                return {'statement_id': path.rsplit('/', 1)[1], 'status': {'state': 'SUCCEEDED'}}
            return {}
        self.settings = DatabricksSettings(self.store, transport)
        self.settings.save({'workspace_url': HOST, 'auth_mode': 'session_token', 'warehouse_id': 'wh1', 'catalog': 'main',
                            'schema': 'mig', 'cli_profile': '', 'revision': 0, 'token': TOKEN})
        self.deploy = DeployService(self.settings, self.store, sleep=lambda s: None)
        run = self.store.create({'files': [{'name': 'a.sql', 'sql': 'SELECT 1'}]})
        self.run_id = run['id']
        conversion = {'files': [{'name': 'a.sql', 'sql': 'CREATE TABLE t (a INT); INSERT INTO t VALUES (1);'},
                                {'name': 'b.sql', 'sql': 'SELECT SLOW FROM t; SELECT * FROM missing;'},
                                {'name': 'migration-coverage.json', 'sql': '{}', 'kind': 'coverage_report'}]}
        with self.store.db() as db:
            db.execute('UPDATE runs SET conversion_json=? WHERE id=?', (json.dumps(conversion), self.run_id))

    def tearDown(self):
        self.store.close(); self.temp.cleanup()

    def wait(self, job_id):
        for _ in range(200):
            status = self.deploy.status(job_id)
            if status['status'] in ('succeeded', 'failed', 'cancelled'):
                return status
            time.sleep(0.01)
        self.fail('deployment did not finish')

    def test_preview_sends_nothing(self):
        before = len(self.calls)
        p = self.deploy.preview({'run_id': self.run_id})
        self.assertEqual(p['statement_count'], 4)
        self.assertEqual(len(self.calls), before)

    def test_null_fix_applied_before_execution(self):
        with self.store.db() as db:
            db.execute('UPDATE runs SET conversion_json=? WHERE id=?', (json.dumps({'files': [{'name': 'u.sql', 'sql': 'CREATE TABLE u (a INT NULL, b INT NOT NULL)'}]}), self.run_id))
        p = self.deploy.preview({'run_id': self.run_id})
        self.assertEqual(p['adjusted'], 1)
        job = self.wait(self.deploy.start({'run_id': self.run_id, 'allow_execution': True, 'revision': 1})['id'])
        sent = [c[2]['statement'] for c in self.calls if c[0] == 'POST' and c[1] == '/api/2.0/sql/statements']
        self.assertEqual(sent, ['CREATE TABLE IF NOT EXISTS u (a INT, b INT NOT NULL)'])
        self.assertEqual(job['status'], 'succeeded')

    def test_schemas_created_first(self):
        with self.store.db() as db:
            db.execute('UPDATE runs SET conversion_json=? WHERE id=?', (json.dumps({'files': [{'name': 'u.sql', 'sql': 'CREATE TABLE `dbo`.`a` (x INT); CREATE TABLE `DBO`.`b` (y INT); CREATE TABLE c (z INT)'}]}), self.run_id))
        p = self.deploy.preview({'run_id': self.run_id})
        self.assertEqual(p['statement_count'], 4)
        self.assertEqual(p['statements'][0]['preview'], 'CREATE SCHEMA IF NOT EXISTS `dbo`')
        p = self.deploy.preview({'run_id': self.run_id, 'create_schemas': False})
        self.assertEqual(p['statement_count'], 3)

    def test_existing_tables_skipped_by_default(self):
        with self.store.db() as db:
            db.execute('UPDATE runs SET conversion_json=? WHERE id=?', (json.dumps({'files': [{'name': 'u.sql', 'sql': 'CREATE TABLE `dbo`.`defRole` (a INT)'}]}), self.run_id))
        stmts = [s['preview'] for s in self.deploy.preview({'run_id': self.run_id})['statements']]
        self.assertEqual(stmts[-1], 'CREATE TABLE IF NOT EXISTS `dbo`.`defRole` (a INT)')
        stmts = [s['preview'] for s in self.deploy.preview({'run_id': self.run_id, 'existing': 'replace'})['statements']]
        self.assertEqual(stmts[-1], 'CREATE OR REPLACE TABLE `dbo`.`defRole` (a INT)')
        stmts = [s['preview'] for s in self.deploy.preview({'run_id': self.run_id, 'existing': 'fail'})['statements']]
        self.assertEqual(stmts[-1], 'CREATE TABLE `dbo`.`defRole` (a INT)')

    def test_continue_after_failure(self):
        self.fail_on = 'INSERT'
        job = self.wait(self.deploy.start({'run_id': self.run_id, 'allow_execution': True, 'on_error': 'continue', 'revision': 1})['id'])
        self.assertEqual(job['status'], 'failed')
        self.assertEqual((job['completed'], job['failed']), (3, 1))
        self.assertEqual([s['status'] for s in job['statements']], ['succeeded', 'failed', 'succeeded', 'succeeded'])
        self.assertIn('1 statement(s) failed and the rest ran', job['message'])

    def test_notebook_only_run_imports_into_workspace(self):
        import base64
        nb = ('# Databricks notebook source\nprint(1)\n\n# COMMAND ----------\n'
              'Package_Load = f"""INSERT INTO dbo.Stg_Customer VALUES (1)"""\nspark.sql(Package_Load)\n')
        conv = {'files': [{'name': 'notebooks/Package_2c63fda5/Package/Package.py', 'sql': nb, 'kind': 'notebook'},
                          {'name': 'workflows/Package_2c63fda5.job.json', 'sql': '{}', 'kind': 'workflow_template'}]}
        with self.store.db() as db:
            db.execute('UPDATE runs SET conversion_json=? WHERE id=?', (json.dumps(conv), self.run_id))
        p = self.deploy.preview({'run_id': self.run_id})
        self.assertEqual(p['statement_count'], 1)
        self.assertIn('Import notebook to /Users/<you>/crosslake_migration/Package_2c63fda5/Package/Package', p['statements'][0]['preview'])
        job = self.wait(self.deploy.start({'run_id': self.run_id, 'allow_execution': True, 'revision': 1})['id'])
        self.assertEqual(job['status'], 'succeeded', job['message'])
        self.assertNotIn('_home', job)
        mkdirs = [c[2] for c in self.calls if c[1] == '/api/2.0/workspace/mkdirs']
        imports = [c[2] for c in self.calls if c[1] == '/api/2.0/workspace/import']
        self.assertEqual(mkdirs, [{'path': '/Users/radhika@example.com/crosslake_migration/Package_2c63fda5/Package'}])
        self.assertEqual(imports[0]['path'], '/Users/radhika@example.com/crosslake_migration/Package_2c63fda5/Package/Package')
        self.assertEqual((imports[0]['format'], imports[0]['language'], imports[0]['overwrite']), ('SOURCE', 'PYTHON', True))
        body = base64.b64decode(imports[0]['content']).decode()
        self.assertIn('spark.sql("USE CATALOG `main`")', body)
        self.assertLess(body.index('USE CATALOG'), body.index('INSERT INTO dbo.Stg_Customer'))
        self.assertIn('INSERT INTO dbo.Stg_Customer VALUES (1)"""', body)
        self.assertFalse(any(c[1] == '/api/2.0/sql/statements' for c in self.calls))

    def test_notebook_folder_validated(self):
        with self.assertRaises(ValueError):
            self.deploy.preview({'run_id': self.run_id, 'notebook_folder': 'C:\\temp'})

    def test_requires_consent(self):
        with self.assertRaises(ValueError):
            self.deploy.start({'run_id': self.run_id, 'revision': 1})

    def test_success_uses_catalog_schema_and_polls(self):
        job = self.wait(self.deploy.start({'run_id': self.run_id, 'allow_execution': True, 'revision': 1})['id'])
        self.assertEqual(job['status'], 'succeeded')
        self.assertEqual(job['completed'], 4)
        posts = [c[2] for c in self.calls if c[0] == 'POST' and c[1] == '/api/2.0/sql/statements']
        self.assertTrue(all(p['catalog'] == 'main' and p['schema'] == 'mig' and p['warehouse_id'] == 'wh1' for p in posts))
        self.assertTrue(any(c[0] == 'GET' for c in self.calls))
        self.assertNotIn(TOKEN, json.dumps(job))

    def test_stops_at_first_failure_with_message(self):
        self.fail_on = 'missing'
        job = self.wait(self.deploy.start({'run_id': self.run_id, 'allow_execution': True, 'revision': 1})['id'])
        self.assertEqual(job['status'], 'failed')
        self.assertIn('TABLE_OR_VIEW_NOT_FOUND', job['message'])
        self.assertEqual(job['completed'], 3)
        events = self.store.get(self.run_id)['events']
        self.assertTrue(any('Deployment failed' in e['message'] for e in events))

    def test_file_selection(self):
        job = self.wait(self.deploy.start({'run_id': self.run_id, 'files': ['a.sql'], 'allow_execution': True, 'revision': 1})['id'])
        self.assertEqual(job['total'], 2)


